export const MEMORY_DELETE_PATTERN =
  /忘掉|忘了|别记|删掉|删除.{0,4}(记忆|偏好|记录)|清除.{0,4}(记忆|偏好)/;

/**
 * 从「忘了我说过不吃辣」里抠出要删的关键词。
 *
 * 后面那串口味 / 预算 / 口感是给侧栏 ✕ 用的：那里点一下发来的是「忘掉辣味」
 * 「忘掉30元内」这类短语，抠不出关键词后端就没法删，
 * 界面上标签没了、服务端还记着，下一轮又带回来——用户会觉得"我明明删了"。
 *
 * ⚠️ **只列偏好对象本身，不许挂动词兜底**。
 * 以前末尾有一条 `喜欢[^，。！？\s]{1,6}`，于是「忘掉我喜欢辣味」抠出来的是
 * 「喜欢辣味」——记忆里存的 keyword 是「辣味」（见 `factsFromMessage` 的 `like[1]`），
 * `includes` 比不中就回"你要我忘掉哪条"，用户明明说了要忘却被当成没说清。
 * 动词前缀交给下面的 `MEMORY_LIKE_PATTERN` 处理。
 *
 * 长的排前面：`辣味` 必须先于 `辣`，否则「辣味」会被切成「辣」，
 * 删的时候虽然靠 `includes` 也能中，但回复里那句"XX这条我删了"就变得很别扭。
 */
export const MEMORY_KEYWORD_PATTERN =
  /不吃辣|不想吃辣|不能吃辣|不碰辣|忌辣|不吃甜|不想吃甜|不要甜|不吃酸|不想吃酸|忌酸|花生过敏|坚果过敏|海鲜过敏|海产品过敏|乳制品过敏|牛奶过敏|乳糖不耐|30元内|30-60元|60元以上|10元内|10-30元|甜味|咸味|酸味|辣味|清淡|嚼感|口感|脆|软|辣|甜|咸|酸|预算/;

/**
 * 「喜欢辣味」「爱吃甜的」「喜欢嚼感」这类正向偏好说法：剥掉动词，只留对象。
 *
 * 只在 `MEMORY_KEYWORD_PATTERN` 一个都没认出来时兜底（比如「忘掉我喜欢薯片」）——
 * 认出来的情况一律走上面那份白名单，避免把「喜欢」这种动词当关键词交给 `deleteMemory`。
 */
export const MEMORY_LIKE_PATTERN =
  /(?:喜欢|爱吃|爱喝|偏爱|偏好|最?爱|就好|就爱|只吃|只爱)(?:吃|喝)?([^，。！？\s]{1,6})/;

