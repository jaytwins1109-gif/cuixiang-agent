/**
 * 「你记得我什么」——**第二视角**的问法，明摆着在问"你手里记着我啥"。
 *
 * 2026-11-09 扩口径：原来只有 `记得我什么|还记得我|记住了什么|你记得|记了什么|知道我不|我的偏好是啥|你还记得`，
 * 「你记住我啥口味了吗」这种「记住我+啥」的变体漏在外面。
 *
 * 又补两类更口语的追问（用户事故原话）：
 *   - 「我不是跟你说过吗」这类**带火气的提醒**：整句就是"你手里有我的记录，拿出来"，
 *     必须本地秒回记忆清单。锚定 `$` 是故意的——「我不是跟你说过我吃辣吗」
 *     后面还带着新信息，不能当纯查询吞掉（那样这句里的偏好就白说了）。
 *   - 「我的偏好呢」：句子就停在"呢/吗/啊"上，不需要「是什么」也照样是提问；
 *     不带语气词的「我的口味比较重」是陈述，不许误判。
 */
export const MEMORY_QUERY_PATTERN =
  /记(住|得)我(什么|啥|多少|哪些)|记(住|得)?了什么|你(还)?记(住|得)我|记得我|知道我不(吃|能|碰)|知道(我)?(的)?(喜好|偏好|忌口|口味|过敏)(是)?(什么|啥)|我的(偏好|忌口|口味)(是|有)?(什么|啥)|我(说过|提过)(什么|啥)|不是(?:早就?|已经)?(?:(?:跟|和|给)你(?:说|讲|提)过|告诉过?你)(?:[了吗嘛啊呀]{0,3})[?？。！!]*$|我的(偏好|忌口|口味)[呢吗啊呀]/;

/**
 * 「我喜欢什么口味」「我喜好啥」——**第一视角**的问法（2026-11-09 用户报的失忆事故）。
 *
 * 事故现场：用户问「我喜欢什么口味」，老规则一条都不命中 → 走大脑；
 * 而记忆为空时提示词里**整段记忆都不给**，模型手里没有任何依据，
 * 张口就是"我哪知道啊，咱俩才聊几句"——既失忆又顶撞人。
 * 所以这类问法必须在本地就落到 `handleMemoryIntent` 的 query 分支，由 `renderMemoryReply` 秒回。
 *
 * 只认「我 + 喜欢/喜好/偏爱/爱 + (可选的吃/喝) + 什么/啥」这种结构，且**不以裸"吃"开头**：
 * 「我吃什么好呢」是在问吃什么，不是问记忆，收进来会把推荐问句打成记忆查询。
 * 中间的"吃/喝"必须允许：「我平时喜欢吃什么来着」是真实问法，
 * 卡死紧邻会把最自然的说法漏出去（2026-11-09 补）。
 */
export const MEMORY_QUERY_SELF_PATTERN =
  /我(?:平时|一般|平常|通常|到底|究竟|都|还|现在)*(喜欢|喜好|偏爱|爱|爱吃|爱喝)(?:吃|喝)?(什么|啥|哪种|哪一类|哪类|哪些|哪个)|我(什么|啥)(口味|忌口|偏好)|我(有什么|有啥)(偏好|忌口|口味|过敏)/;

/**
 * 授权语气：「我喜欢什么都行，你看着推」——这是放权，不是问记忆。
 * 拿一张"记着这些：…"的清单回他，答非所问。
 */
export const MEMORY_QUERY_DEFER_PATTERN = /都行|都可以|随便|你看着|听你的|就推|推荐吧|不用问/;

/** 全清：用户要一次性重来。必须先于单条删除判断，否则「全都忘掉」会被当成删某一条 */
export const MEMORY_CLEAR_PATTERN =
  /全都?忘掉|全部?忘掉|都忘掉|忘掉所有|忘了所有|清空记忆|清空所有|删除所有记忆/;

/** 单条删除意图 */
export const MEMORY_DELETE_PATTERN =
  /忘掉|忘了|别记|删掉|删除.{0,4}(记忆|偏好|记录)|清除.{0,4}(记忆|偏好)/;

/**
 * 从「忘了我说过不吃辣」里抠出要删的关键词。
 *
 * 后面那串口味 / 预算 / 口感是给侧栏 ✕ 用的：那里点一下发来的是「忘掉辣味」
 * 「忘掉30元内」这类短语，抠不出关键词后端就没法删，
 * 界面上标签没了、服务端还记着，下一轮又带回来——用户会觉得"我明明删了"。
 *
 * ⚠️ **只列偏好对象本身，不许挂动词兜底**。
 * 以前末尾有一条 `喜欢[^，。！？\s]{1,6}`，于是「忘掉我喜欢辣味」抠出来的是
 * 「喜欢辣味」——记忆里存的 keyword 是「辣味」（见 `factsFromMessage` 的 `like[1]`），
 * `includes` 比不中就回"你要我忘掉哪条"，用户明明说了要忘却被当成没说清。
 * 动词前缀交给下面的 `MEMORY_LIKE_PATTERN` 处理。
 *
 * 长的排前面：`辣味` 必须先于 `辣`，否则「辣味」会被切成「辣」，
 * 删的时候虽然靠 `includes` 也能中，但回复里那句"XX这条我删了"就变得很别扭。
 */
export const MEMORY_KEYWORD_PATTERN =
  /不吃辣|不想吃辣|不能吃辣|不碰辣|忌辣|不吃甜|不想吃甜|不要甜|不吃酸|不想吃酸|忌酸|花生过敏|坚果过敏|海鲜过敏|海产品过敏|乳制品过敏|牛奶过敏|乳糖不耐|30元内|30-60元|60元以上|10元内|10-30元|甜味|咸味|酸味|辣味|清淡|嚼感|口感|脆|软|辣|甜|咸|酸|预算/;

/**
 * 「喜欢辣味」「爱吃甜的」「喜欢嚼感」这类正向偏好说法：剥掉动词，只留对象。
 *
 * 只在 `MEMORY_KEYWORD_PATTERN` 一个都没认出来时兜底（比如「忘掉我喜欢薯片」）——
 * 认出来的情况一律走上面那份白名单，避免把「喜欢」这种动词当关键词交给 `deleteMemory`。
 */
