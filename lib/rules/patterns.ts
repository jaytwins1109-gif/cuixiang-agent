// lib/rules/patterns.ts
//
// 「怎么判断用户这句话是什么意思」的全部规则表达式，集中放在这里。
//
// 为什么抽出来：这些正则原本散在三个文件里——
//   · lib/llm/index.ts          意图防呆、偏好兜底抽取、文本清洗
//   · app/api/ai/route.ts       记忆意图、待确认答复、铺垫钩子
//   · lib/llm/local-workflow.ts 送礼 / 夜间场景判断
// 想调一句"什么样算开口要"，要在三个文件里来回翻。现在改口径只改这一个文件。
//
// ⚠️ 改这里 = 改提示词的行为，必须同步跑 `npm run smoke`。

// ─── 意图防呆（lib/llm/index.ts → allowRecommend）────────────────
//
// 判定顺序：**先拒 REFUSE → 再看 BUY → 再看「在推荐上下文里 且 命中 ADJUST」**。
// 「不想吃东西了」里含「不想吃」，会撞上改条件规则，但它其实是撤单——所以 REFUSE 必须排第一。

/** 撤单信号：不想吃了 / 没胃口 / 算了。优先级最高，命中即不再推荐 */
export const REFUSE_PATTERN = /不想吃(东西|了)|不吃了|吃不下|没胃口|不饿|饱了|算了吧|算了.*不吃/;

/** 明确开口要：推荐 / 来点 / 想吃 / 买个 … */
export const BUY_PATTERN =
  /推荐|推个|来个|来点|来份|来一[袋包盒份]|整点|整一|想吃|要吃|吃点|买点|买个|买一|带点|有啥好吃|有什么好吃|好吃[的]?推荐|挑点|挑个|选点|来点吃|什么吃的|啥吃的|看看有/;

/** 推荐上下文里改条件：太贵 / 换一个 / 不要 / 过敏 / 有没有别的 */
export const ADJUST_PATTERN =
  /太贵|便宜|换[一个批]|不要|不吃|不想吃|有别[的]|别的|其他|另外|过敏|除了|有没有/;

/**
 * 顺着铺垫点头：随便 / 都行 / 听你的，或单独一个「好 / 要 / 行 / 来 / ok」。
 * **只在推荐上下文里算数**——闲聊里一个"嗯""好"就把货推出去，等于自动推荐，人设不许。
 * 收得很紧：核心词后面允许语气词、停顿和短尾巴（"好的，来点""行，随便"都是同意），
 * 但出现转折或新内容（"好啊那我不买了""好，然后呢"）就不算——尾部放宽、整句仍钉死。
 */
export const CONSENT_PATTERN =
  /随便|都行|都可以|都好|你看着[办选]|听你的|^(好|要|行|来|ok|OK)(啊|呀|吧|的|哦|啦)*[\s,，。.]*(来点|随便|都行|都好|你看着办)?[!！。.,，]?$/;

/** 明显在打听某个商品：「火鸡面啥样」「魔芋爽怎么吃」 */
export const INTRODUCE_PATTERN =
  /啥样|什么样|怎么样|介绍一下|介绍下|讲讲|说说|是什么|怎么吃|好吃吗|啥味道/;

/**
 * 硬要 / 死磕：用户用强制性句式点名要某样东西（"我非要点""偏要""铁了心要"）。
 *
 * 单独命中它什么都不做——有人认准了一款很正常。
 * 它只在**点名的东西撞上忌口**时才触发本地拦截，见 `handleInsistAvoid`。
 */
export const INSIST_PATTERN =
  /非要点|非得要|非得|非要|偏要|我就要|铁了心|死活要|执意|一定要|就认准/;

/**
 * 催货信号：上一轮已经"画了饼"（说要挑几样 / 抛了钩子），这轮用户追着要货。
 *
 * 「你说说」「那几样呢」「哪几样呢？」是**极强的要货信号**——
 * 人都已经点头了，再陪聊一轮就是把人晾着，体验上等于问了三遍才有货。
 * 命中即升 recommend。
 *
 * 收得很紧，两个条件同时满足才算：
 *   1. **整句匹配**（不能是"你说说火鸡面"那种带宾语的，那是打听单品，走 introduce）
 *   2. 只认这几个催货词 + 语气词 + 标点
 */
export const URGE_PATTERN =
  /^(那|所以|到底)?(几样|几款|哪几样|哪几款|哪样|哪款|都有啥|有啥|说说呗|说说看|你说说|说来听听|说来看看|说啊|讲讲呗)[呢啊呀呗]?[？?。!！~\s]*$/;

