/**
 * 【当前用户信息】（2026-11-10）：昵称由服务端账号表注入，不是模型自己猜的。
 *
 * 两条纪律：
 *   - 没传昵称就**一个字都不加**——空段落反而会让模型去编一个称呼出来；
 *   - 昵称会拼在 system 最顶部，这里再洗一次换行 / 引号 / 方括号
 *     （`lib/auth/nickname.ts` 入库前已经洗过，这一层是防止别的调用方绕过）。
 */
const NICKNAME_UNSAFE = /["'`\\<>()[\]{}【】#\s]/;

function nicknameSection(nickname?: string | null): string {
  // 按码点过滤控制字符：写 [\u0000-\u001f] 会被 ESLint no-control-regex 拦，
  // 而且这样连 C1 控制符一起挡掉。口径与 lib/auth/nickname.ts 的 safeText 一致。
  const clean = Array.from(String(nickname || ''))
    .filter((ch) => {
      const code = ch.codePointAt(0) ?? 0;
      return code > 31 && code !== 127 && !NICKNAME_UNSAFE.test(ch);
    })
    .join('')
    .slice(0, 24);
  if (!clean) return '';
  return `【当前用户信息】用户昵称是“${clean}”，请像朋友一样自然地称呼他，不要每句话都带，但在打招呼或回应时可以使用。\n\n`;
}

